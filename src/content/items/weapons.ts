// Reading WORLD's columns (conventions before §7.1; D-085, D-087):
//   Rarity   `roll` = the default rolled rule; `fixed U/R/E` = `rarityRule: 'fixed'` + `fixedRarity`, the listed affixes in
//            `fixedAffixes` (a fixed piece with none lists none: the tier's affix count rolls); `craft` = fixed Common, the
