//   Effects  `spell_power` → `spellPower`; `on_hit` → a `statusOnHit` passive; `self_cost_hp` → the `curse` passive's `damage`;
//            `resist <type>` → `resistSteps`; `dmg_bonus` → `damageBonus`; `life_steal` → `lifeSteal`; `mp_cost_reduction` →
//            `mpCostReduction`; `mp_regen` → a `regen` passive. Percentages are fractions (10% = 0.1).
//   Scripts  Where no passive kind says what WORLD says, a `custom` passive carries the number (the affixes' pattern,
